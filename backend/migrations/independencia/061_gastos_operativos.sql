-- Combustible y alimentación usan el buzón, compra sin producto y CxP existentes.
-- Recibir no paga ni acepta fiscalmente. Ningún proveedor cambia de flujo.
BEGIN;

ALTER TABLE proveedor ADD COLUMN IF NOT EXISTS tratamiento_facturas TEXT NOT NULL DEFAULT 'comercial'
  CHECK (tratamiento_facturas IN ('comercial', 'combustible', 'alimentacion', 'mixto'));
ALTER TABLE facturas_proveedores ADD COLUMN IF NOT EXISTS tratamiento TEXT NOT NULL DEFAULT 'comercial'
  CHECK (tratamiento IN ('comercial', 'combustible', 'alimentacion', 'mixto'));
ALTER TABLE facturas_proveedores ADD COLUMN IF NOT EXISTS pdf_ruta TEXT;
CREATE INDEX IF NOT EXISTS idx_proveedor_identificacion_tributaria ON proveedor
  (ltrim(regexp_replace(identificacion, '[[:space:]-]', '', 'g'), '0'));

-- Reintentar un pago tras perder conexión devuelve el pago real, sin otra salida.
ALTER TABLE pago_proveedor ADD COLUMN IF NOT EXISTS clave_idempotencia UUID;
ALTER TABLE pago_proveedor ADD COLUMN IF NOT EXISTS huella_idempotencia TEXT;
CREATE UNIQUE INDEX IF NOT EXISTS idx_pago_proveedor_idempotencia ON pago_proveedor(clave_idempotencia)
  WHERE clave_idempotencia IS NOT NULL;

-- El estado GASTO_RECURRENTE ya excluye documentos sin catálogo del flujo
-- comercial. Se reutiliza: el cliente Prisma compartido no conoce enums nuevos.
CREATE TABLE IF NOT EXISTS gasto_operativo (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  factura_id UUID NOT NULL UNIQUE REFERENCES facturas_proveedores(id),
  compra_id INTEGER UNIQUE REFERENCES compra(id),
  categoria TEXT NOT NULL CHECK (categoria IN ('combustible', 'alimentacion')),
  descripcion TEXT NOT NULL,
  empleado TEXT,
  placa TEXT,
  originales JSONB NOT NULL,
  validacion TEXT NOT NULL CHECK (validacion IN ('validado', 'requiere_revision')),
  motivo_validacion TEXT,
  iva_maximo NUMERIC(18,5) NOT NULL DEFAULT 0 CHECK (iva_maximo >= 0),
  renta TEXT NOT NULL DEFAULT 'pendiente' CHECK (renta IN ('pendiente', 'deducible', 'parcial', 'no_deducible')),
  gasto_deducible NUMERIC(18,5) NOT NULL DEFAULT 0 CHECK (gasto_deducible >= 0),
  iva TEXT NOT NULL DEFAULT 'pendiente' CHECK (iva IN ('pendiente', 'total', 'parcial', 'sin_credito')),
  iva_credito NUMERIC(18,5) NOT NULL DEFAULT 0 CHECK (iva_credito >= 0 AND iva_credito <= iva_maximo),
  respuesta TEXT CHECK (respuesta IN ('1', '2', '3')),
  motivo_fiscal TEXT,
  revisado_por INTEGER REFERENCES usuario(id),
  revisado_en TIMESTAMPTZ,
  version INTEGER NOT NULL DEFAULT 1,
  creado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
  actualizado_en TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS gasto_operativo_categoria_fecha ON gasto_operativo(categoria, creado_en DESC, id DESC);
CREATE INDEX IF NOT EXISTS gasto_operativo_revision ON gasto_operativo(creado_en DESC) WHERE revisado_en IS NULL;

-- Una relación accidental o una llamada al kardex no convierte un almuerzo en stock.
CREATE OR REPLACE FUNCTION impedir_producto_en_gasto_operativo() RETURNS TRIGGER AS $$
BEGIN
  IF NEW.producto_id IS NOT NULL AND EXISTS (SELECT 1 FROM gasto_operativo WHERE compra_id = NEW.compra_id) THEN
    RAISE EXCEPTION 'Un gasto operativo no puede tener productos de inventario';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS gasto_sin_producto ON compra_linea;
CREATE TRIGGER gasto_sin_producto BEFORE INSERT OR UPDATE ON compra_linea
  FOR EACH ROW EXECUTE FUNCTION impedir_producto_en_gasto_operativo();

CREATE OR REPLACE FUNCTION impedir_relacion_en_gasto_operativo() RETURNS TRIGGER AS $$
BEGIN
  IF (NEW.producto_id IS NOT NULL OR NEW.mapeo_id IS NOT NULL) AND EXISTS (
    SELECT 1 FROM facturas_proveedores WHERE id=NEW.factura_id AND tratamiento IN ('combustible','alimentacion')
  ) THEN
    RAISE EXCEPTION 'Las líneas de un gasto operativo son respaldo documental, no catálogo';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS gasto_sin_relacion ON productos_factura_proveedor;
CREATE TRIGGER gasto_sin_relacion BEFORE INSERT OR UPDATE ON productos_factura_proveedor
  FOR EACH ROW EXECUTE FUNCTION impedir_relacion_en_gasto_operativo();

COMMIT;
